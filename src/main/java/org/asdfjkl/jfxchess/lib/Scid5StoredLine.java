    public Scid5StoredLine(Board targetBoard, int targetTurn) {
        matches[0] = -1;
        matches[STORED_LINES] = -1;

        if (targetBoard == null) {
            Arrays.fill(matches, (byte) -1);
            return;
        }

        boolean hasWildcards = false;
        int[] searchPieces = new int[64];
        for (int sq = 0; sq < 64; sq++) {
            searchPieces[sq] = targetBoard.getPieceAt(sq & 7, sq >> 3);
            if (searchPieces[sq] == WHITE_ANY_PIECE || searchPieces[sq] == BLACK_ANY_PIECE) {
                hasWildcards = true;
            }
        }

        // Play each of the 254 stored lines on a lightweight 64-square board
        for (int line = 1; line < STORED_LINES; line++) {
            int startIdx = MOVES_OFFSETS[line];
            int endIdx = MOVES_OFFSETS[line + 1];
            int lineLen = endIdx - startIdx;

            int[] b = createStdBoard();
            byte result = -1;

            for (int ply = 0; ply <= lineLen; ply++) {
                boolean isWhite = (ply % 2 == 0);
                boolean turnMatch = (targetTurn == SearchPattern.TURN_ANY)
                        || (targetTurn == SearchPattern.TURN_WHITE && isWhite)
                        || (targetTurn == SearchPattern.TURN_BLACK && !isWhite);

                if (turnMatch && isBoardEqual(b, searchPieces)) {
                    result = (byte) ply;
                    break;
                }

                if (ply == lineLen) {
                    result = neverMatch(b, searchPieces, hasWildcards) ? (byte) -2 : (byte) -1;
                    break;
                }

                int move = FM[startIdx + ply];
                doMove(b, move);
            }

            matches[line] = result;
        }
    }

    public int match(int storedLineCode) {
        if (storedLineCode < 0 || storedLineCode > STORED_LINES) {
            return -1;
        }
        return matches[storedLineCode];
    }

    private static int[] createStdBoard() {
        int[] b = new int[64];
        b[0] = WHITE_ROOK;   b[1] = WHITE_KNIGHT; b[2] = WHITE_BISHOP; b[3] = WHITE_QUEEN;
        b[4] = WHITE_KING;   b[5] = WHITE_BISHOP; b[6] = WHITE_KNIGHT; b[7] = WHITE_ROOK;
        for (int i = 8; i < 16; i++) b[i] = WHITE_PAWN;
        for (int i = 16; i < 48; i++) b[i] = EMPTY;
        for (int i = 48; i < 56; i++) b[i] = BLACK_PAWN;
        b[56] = BLACK_ROOK;  b[57] = BLACK_KNIGHT; b[58] = BLACK_BISHOP; b[59] = BLACK_QUEEN;
        b[60] = BLACK_KING;  b[61] = BLACK_BISHOP; b[62] = BLACK_KNIGHT; b[63] = BLACK_ROOK;
        return b;
    }

    private static void doMove(int[] b, int m) {
        int to = m & 0x3F;
        int from = (m >> 6) & 0x3F;
        boolean isCastle = ((m >> 14) & 3) == 3;

        if (!isCastle) {
            b[to] = b[from];
            b[from] = EMPTY;
        } else {
            int king = b[from];
            int rook = b[to];
            b[from] = EMPTY;
            b[to] = EMPTY;
            if (to > from) {
                b[from + 2] = king;
                b[from + 1] = rook;
            } else {
                b[from - 2] = king;
                b[from - 1] = rook;
            }
        }
    }

    private static boolean isBoardEqual(int[] b, int[] target) {
        for (int i = 0; i < 64; i++) {
            int t = target[i];
            int c = b[i];
            if (t == EMPTY) {
                if (c != EMPTY) return false;
            } else if (t == WHITE_ANY_PIECE) {
                if (c < WHITE_PAWN || c > WHITE_KING) return false;
            } else if (t == BLACK_ANY_PIECE) {
                if (c < BLACK_PAWN || c > BLACK_KING) return false;
            } else {
                if (c != t) return false;
            }
        }
        return true;
    }

    private static boolean neverMatch(int[] b, int[] target, boolean hasWildcards) {
        for (int i = 0; i < 64; i++) {
            int cur = b[i];
            int tgt = target[i];

            // 1. A pawn will never go back to its home square
            int row = i >> 3;
            if (tgt == WHITE_PAWN && cur != WHITE_PAWN && row == 1) return true;
            if (tgt == BLACK_PAWN && cur != BLACK_PAWN && row == 6) return true;
        }

        if (!hasWildcards) {
            int[] pW = new int[7];
            int[] pB = new int[7];
            for (int i = 0; i < 64; i++) {
                int cur = b[i];
                int tgt = target[i];
                if (cur >= WHITE_PAWN && cur <= WHITE_KING) pW[cur - WHITE_PAWN + 1]++;
                if (tgt >= WHITE_PAWN && tgt <= WHITE_KING) pW[tgt - WHITE_PAWN + 1]--;
                if (cur >= BLACK_PAWN && cur <= BLACK_KING) pB[cur - BLACK_PAWN + 1]++;
                if (tgt >= BLACK_PAWN && tgt <= BLACK_KING) pB[tgt - BLACK_PAWN + 1]--;
            }
            int dfW = 0, dfB = 0;
            // Knight (2), Bishop (3), Rook (4), Queen (5)
            for (int t = 2; t <= 5; t++) {
                if (pW[t] < 0) dfW -= pW[t];
                if (pB[t] < 0) dfB -= pB[t];
            }
            // Pawn is index 1
            if (pW[1] < dfW || pB[1] < dfB) return true;
        }

        return false;
    }
